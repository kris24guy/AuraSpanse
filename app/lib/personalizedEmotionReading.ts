import { buildEmotionGlossaryPoints } from './emotionGlossary'
import { emotionColors } from './emotionColors'

export interface EmotionReadingSource {
  name: string
  hex: string
}

export interface EmotionReadingComponent {
  emotion: string
  sourceName: string
  definition: string
  hex: string
}

export interface PersonalizedEmotionReading {
  title: string
  definition: string
  components: EmotionReadingComponent[]
}

export class PersonalizedReadingError extends Error {
  readonly status: number

  constructor(message: string, status = 503) {
    super(message)
    this.name = 'PersonalizedReadingError'
    this.status = status
  }
}

const normalizeName = (value: string) => value.normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, ' ')
  .trim()

const glossaryPoints = buildEmotionGlossaryPoints(emotionColors)
const glossaryByName = new Map(
  glossaryPoints.map((point) => [normalizeName(point.name), point])
)

function rgb(hex: string): [number, number, number] {
  const value = hex.slice(1)
  return [0, 2, 4].map((offset) => Number.parseInt(value.slice(offset, offset + 2), 16)) as [number, number, number]
}

function colorDistance(first: string, second: string): number {
  const a = rgb(first)
  const b = rgb(second)
  return a.reduce((sum, channel, index) => sum + (channel - b[index]) ** 2, 0)
}

function resolveFiveComponents(sources: EmotionReadingSource[]): EmotionReadingComponent[] {
  if (sources.length < 5) {
    throw new PersonalizedReadingError('The Aurascope reading did not produce five emotion colors. Please recalculate and try again.', 422)
  }

  const used = new Set<string>()
  const components: EmotionReadingComponent[] = []

  for (const source of sources) {
    if (!source || typeof source.name !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(source.hex)) continue
    const exact = glossaryByName.get(normalizeName(source.name))
    const candidates = exact
      ? [exact, ...glossaryPoints.filter((point) => point.name !== exact.name)
          .sort((a, b) => colorDistance(a.hex, source.hex) - colorDistance(b.hex, source.hex))]
      : [...glossaryPoints]
          .sort((a, b) => colorDistance(a.hex, source.hex) - colorDistance(b.hex, source.hex))
    const match = candidates.find((point) => !used.has(normalizeName(point.name)))
    if (!match) continue
    used.add(normalizeName(match.name))
    components.push({
      emotion: match.name,
      sourceName: source.name,
      definition: match.definition,
      hex: source.hex.toUpperCase(),
    })
    if (components.length === 5) break
  }

  if (components.length !== 5) {
    throw new PersonalizedReadingError('The Aurascope reading could not resolve five distinct emotion definitions. Please recalculate and try again.', 422)
  }
  return components
}

const SYSTEM_PROMPT = `You are a literary lexicographer writing a personal Aurascope reading. Given exactly five emotion labels and their source definitions, create one original, cohesive definition of the emotional state they form together.

Make the five forces interact as one psychologically coherent state. Preserve meaningful tensions and paradoxes instead of smoothing them away. Do not list the five emotions, concatenate their definitions, or write a horoscope. Stay grounded in the supplied definitions; use the source color values only as subtle palette context, never as evidence of personality or as a source of invented emotional meanings. Do not invent personal facts, causes, predictions, diagnoses, or clinical claims. Write with vivid but restrained language, precision, warmth, and emotional intelligence.

Return a short, memorable title of 2–5 words and one definition of 2–3 sentences, 45–75 words. The definition must stand on its own as a personalized glossary entry. Do not mention that it was generated by AI or that it combines five inputs.`

const RESPONSE_SCHEMA = {
  name: 'aurascope_personal_reading',
  strict: true,
  schema: {
    type: 'object',
    properties: {
      title: { type: 'string' },
      definition: { type: 'string' },
    },
    required: ['title', 'definition'],
    additionalProperties: false,
  },
}

export async function generatePersonalizedEmotionReading(
  sources: EmotionReadingSource[],
): Promise<PersonalizedEmotionReading> {
  const components = resolveFiveComponents(sources)
  const apiKey = process.env.AURASCOPE_AI_API_KEY || process.env.OPENAI_API_KEY
  const model = process.env.AURASCOPE_AI_MODEL
  const baseUrl = (
    process.env.AURASCOPE_AI_BASE_URL ||
    process.env.OPENAI_BASE_URL ||
    process.env.OPENAI_API_BASE ||
    'https://api.openai.com/v1'
  ).replace(/\/+$/, '')

  if (!apiKey || !model) {
    console.error('[Aurascope reading] AI configuration is missing.')
    throw new PersonalizedReadingError('The personalized reading service is not configured yet. Please try again later.')
  }

  let response: Response
  try {
    response = await fetch(`${baseUrl}/chat/completions`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model,
        messages: [
          { role: 'system', content: SYSTEM_PROMPT },
          {
            role: 'user',
            content: JSON.stringify(components.map(({ emotion, definition, hex }) => ({
              emotion,
              definition,
              sourceColorHex: hex,
            }))),
          },
        ],
        response_format: {
          type: 'json_schema',
          json_schema: RESPONSE_SCHEMA,
        },
        max_completion_tokens: 700,
      }),
      signal: AbortSignal.timeout(25_000),
    })
  } catch (error) {
    console.error('[Aurascope reading] AI request failed:', error instanceof Error ? error.message : 'unknown error')
    throw new PersonalizedReadingError('The personalized reading could not be generated right now. Please try again.')
  }

  if (!response.ok) {
    console.error('[Aurascope reading] AI provider returned status', response.status)
    throw new PersonalizedReadingError('The personalized reading could not be generated right now. Please try again.')
  }

  let payload: any
  try {
    payload = await response.json()
  } catch {
    throw new PersonalizedReadingError('The personalized reading service returned an invalid response. Please try again.')
  }

  const content = payload?.choices?.[0]?.message?.content
  if (typeof content !== 'string') {
    throw new PersonalizedReadingError('The personalized reading service returned an empty response. Please try again.')
  }

  let parsed: { title?: unknown; definition?: unknown }
  try {
    parsed = JSON.parse(content)
  } catch {
    throw new PersonalizedReadingError('The personalized reading service returned an invalid response. Please try again.')
  }

  const title = typeof parsed.title === 'string' ? parsed.title.trim() : ''
  const definition = typeof parsed.definition === 'string' ? parsed.definition.trim() : ''
  const wordCount = definition.split(/\s+/).filter(Boolean).length
  if (!title || title.length > 80 || wordCount < 35 || wordCount > 95) {
    throw new PersonalizedReadingError('The personalized reading service returned an incomplete reading. Please try again.')
  }

  return { title, definition, components }
}

export function hasPersonalizedReadingConfig(): boolean {
  return Boolean(
    (process.env.AURASCOPE_AI_API_KEY || process.env.OPENAI_API_KEY) &&
    process.env.AURASCOPE_AI_MODEL
  )
}
